#!/usr/bin/env node
// Game-by-game reconciliation report for the replay (task R14, Gate B).
//
// Usage:
//   node scripts/replay-report.mjs [fixtureId…] > docs/replay-implementation/reconciliation-report.md
//   node scripts/replay-report.mjs --json [fixtureId…]
//
// Reads tests/fixtures/replay/*.json (manifest.json). Never fetches. Runs the
// real pipeline: normalizeGame → buildStateIndex → validateReplay.

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeGame } from "../lib/replay/normalize.js";
import { buildStateIndex } from "../lib/replay/state.js";
import { validateReplay } from "../lib/replay/validate.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURE_DIR = join(ROOT, "tests/fixtures/replay");
const args = process.argv.slice(2);
const asJson = args.includes("--json");
const manifest = JSON.parse(readFileSync(join(FIXTURE_DIR, "manifest.json"), "utf8"));
const ids = args.filter((a) => !a.startsWith("--"));
const fixtureIds = ids.length ? ids : Object.keys(manifest.fixtures);

const results = fixtureIds.map((id) => {
  const summary = JSON.parse(readFileSync(join(FIXTURE_DIR, `${id}.json`), "utf8"));
  const n = normalizeGame(summary);
  const v = validateReplay(n, buildStateIndex(n));
  return { id, n, v };
});

if (asJson) {
  console.log(JSON.stringify(results.map(({ id, v }) => ({ id, ...v })), null, 2));
  process.exit(0);
}

const lines = [];
const out = (s = "") => lines.push(s);
const yes = (b) => (b === true ? "✓" : b === false ? "✗" : "—");
const COUNTERS = ["pts", "fgm", "fga", "tpm", "tpa", "ftm", "fta", "reb", "oreb", "dreb", "ast", "to", "stl", "blk", "pf"];

out("# Replay reconciliation report (Gate B)");
out();
out("Generated by `node scripts/replay-report.mjs > docs/replay-implementation/reconciliation-report.md` from the committed fixtures (`tests/fixtures/replay/`). Pipeline: `normalizeGame` → `buildStateIndex` → `validateReplay` (`lib/replay/validate.js`). Box score and header are validation only; no end-state value is patched.");
out();
out("Definitions: team REB/OREB/DREB in the box exclude team rebounds, so team totals compare player sum + unattributed credit; team rebounds (`teamReb`) have no box counterpart and are not validated. Box `turnovers` = player turnovers, `teamTurnovers` = team-only `teamTo`, `totalTurnovers` = both. `technicalFouls` is a team-only counter (never PF).");
out();
out("## Summary");
out();
out("| Game | Matchup | Status | Reasons | Player values matched | Score / periods | Lineups (home, away) | Probability |");
out("| --- | --- | --- | --- | --- | --- | --- | --- |");
for (const { id, n, v } of results) {
  const m = manifest.fixtures[id];
  const { score, players } = v.reconciliation ?? {};
  const scoreOk = score && ["home", "away"].every((s) => score.final[s].source === score.final[s].expected && score.final[s].credited === score.final[s].expected);
  const periodsOk = score && score.periods.every((p) => p.match);
  const lu = [n.teams.home.id, n.teams.away.id].map((t) => `${v.lineups[t].abbreviation}: ${v.lineups[t].evidence.level}`).join(", ");
  out(`| ${id} | ${n.teams.away.abbreviation} @ ${n.teams.home.abbreviation} ${n.teams.away.finalScore}–${n.teams.home.finalScore}${m?.label ? ` (${m.label})` : ""} | **${v.status}** | ${v.reasons.join(", ") || "—"} | ${players.matched}/${players.checked} | ${yes(scoreOk)} / ${yes(periodsOk)} (${score.periods.length}) | ${lu} | ${v.probability.samples}/${v.probability.events} linked |`);
}
out();

for (const { id, n, v } of results) {
  const name = (pid) => n.players.find((p) => p.id === pid)?.name ?? pid;
  out(`## ${id} — ${n.teams.away.abbreviation} @ ${n.teams.home.abbreviation}: **${v.status}**`);
  out();
  out(`Reasons: ${v.reasons.join(", ") || "none"}. Warnings: ${v.warnings.map((w) => `${w.code}×${w.count}`).join(", ") || "none"}.`);
  out();

  const { score, players, teams } = v.reconciliation;
  out("### Score");
  out();
  out("| | Source final | Credited final | Header | " + score.periods.map((p) => (p.period <= 4 ? `Q${p.period}` : `OT${p.period - 4}`)).join(" | ") + " |");
  out("| --- | --- | --- | --- | " + score.periods.map(() => "---").join(" | ") + " |");
  for (const side of ["away", "home"]) {
    const f = score.final[side];
    const per = score.periods.map((p) => `${p[side].actual}${p[side].actual === p[side].expected ? "" : ` (box ${p[side].expected})`}`);
    out(`| ${n.teams[side].abbreviation} | ${f.source} | ${f.credited} | ${f.expected} | ${per.join(" | ")} |`);
  }
  out();

  out("### Players");
  out();
  out(`${players.matched}/${players.checked} player values reconcile.`);
  if (players.mismatches.length) {
    out();
    out("| Player | Counter | Reconstructed | Box | Treatment |");
    out("| --- | --- | --- | --- | --- |");
    for (const m of players.mismatches) {
      const cap = v.capabilities.find((c) => c.scope === "player" && c.family === m.family && c.players.includes(m.playerId));
      out(`| ${m.name} (${m.playerId}) | ${m.counter} | ${m.reconstructed} | ${m.expected} | \`${m.family}\` ${cap?.level ?? "?"} for this player (${cap?.reasons.join(", ")}) |`);
    }
  }
  if (players.unattributed.length) {
    out();
    for (const u of players.unattributed) out(`- Unattributed: ${u.amount} ${u.counter} for team ${teams[u.teamId].abbreviation}; ${u.explainedBy.length ? `explained by ${u.explainedBy.map(name).join(", ")}'s mismatch` : "not explained by any mismatch → team-scoped limitation"}.`);
  }
  if (players.unverified.length) {
    out();
    for (const u of players.unverified) out(`- Unverifiable: ${u.name} ${u.counter} = ${u.reconstructed} (box has no value).`);
  }
  out();

  out("### Team totals (player sum + unattributed vs box)");
  out();
  out("| Team | " + COUNTERS.join(" | ") + " | teamTo | totalTo | tech | teamReb (unvalidated) |");
  out("| --- | " + COUNTERS.map(() => "---").join(" | ") + " | --- | --- | --- | --- |");
  for (const side of ["away", "home"]) {
    const t = teams[n.teams[side].id];
    const cell = (c) => (c.expected == null ? `${c.total ?? c.value} (—)` : c.match ? `${c.total ?? c.value}` : `**${c.total ?? c.value} ≠ ${c.expected}**`);
    out(`| ${t.abbreviation} | ${COUNTERS.map((k) => cell(t.counters[k])).join(" | ")} | ${cell(t.teamOnly.teamTo)} | ${cell(t.teamOnly.totalTo)} | ${cell(t.teamOnly.technicalFouls)} | ${t.teamOnly.teamReb.value} |`);
  }
  out();

  out("### Lineups");
  out();
  out("| Team | Valid states | Fallback intervals | Invariant violations | Actor checks (violations) | Stints with an action | Final five = box active | Evidence |");
  out("| --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const side of ["away", "home"]) {
    const l = v.lineups[n.teams[side].id];
    const iv = l.fallbackIntervals.map((i) => `${i.from}–${i.to} (${i.reasons.join(", ")})`).join("; ") || "none";
    out(`| ${l.abbreviation} | ${l.validStates}/${l.totalStates} | ${iv} | ${l.invariantViolations.length} | ${l.evidence.actorChecks} (${l.evidence.actorViolations}) | ${l.evidence.stints.withAction}/${l.evidence.stints.total} | ${yes(l.evidence.finalMatchesActive)} | ${l.evidence.level} |`);
  }
  out();
  out(`Probability: ${v.probability.samples}/${v.probability.events} events linked, first at event ${v.probability.firstEventIndex}, ${v.probability.derived} derived, discarded ${JSON.stringify(v.probability.discarded)}.`);
  out();
  const limited = v.capabilities.filter((c) => c.level !== "reliable");
  out("### Capabilities below reliable");
  out();
  if (!limited.length) out("None — every family reliable.");
  for (const c of limited) {
    const target = c.players ? `: ${c.players.map(name).join(", ")}` : c.teams ? `: team ${c.teams.join(", ")}` : "";
    const interval = c.interval ? ` events ${c.interval.from}–${c.interval.to}` : "";
    out(`- \`${c.family}\` [${c.scope}${target}${interval}]: **${c.level}** (${c.reasons.join(", ")})`);
  }
  out();
}

out("## Gate B notes");
out();
out("- Lineup evidence levels: `corroborated` = no fallback, no structural violation, every on-court actor inside the tracked five, final five equals the box `active` five. Five distinct players alone is only structural; stints without any recorded action are listed because they are not independently evidenced (the player may simply not have touched the ball).");
out("- Classification defaults (tunable via `validateReplay` options): >2% of events without period/clock → unavailable; a stat family is disabled game-wide when ≥3 players and ≥20% of verified players mismatch (fewer → disabled for those players only); a tracked final five ≠ box `active` limits that team's lineup from its last substitution to the end.");
out("- Missing End of Game, or no end marker for the last period, → unavailable (truncated play-by-play). Missing header linescores is deliberately only a `period_scores_missing` warning (status can stay ready; final score and end markers still checked). Final requires completed + state `post` + `STATUS_FINAL*`.");
out("- Holland II (401810792): FGA reconciles (13 = 13) and only 3PA differs (6 vs 5), so one attempt is a 2 in the box but a 3 in the play text. FG stays reliable; 3PT is disabled for him and the DET team 3PT total is labeled. Consumers must not derive 2PT as FG − 3PT for a player whose `tpt` is unavailable.");
out("- Porter Jr. (401810062): the block in play 401810062656 names Demin as participant but Porter Jr. in text; the credit stays team-level (`unattributed`), so the BKN team block total reconciles while Porter Jr.'s running BLK is unavailable.");
console.log(lines.join("\n"));
