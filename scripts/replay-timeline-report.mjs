#!/usr/bin/env node
// Replay timeline report (tasks R19–R20).
//
// Usage:
//   node scripts/replay-timeline-report.mjs [fixtureId…]          # writes docs/replay-implementation/timeline-report.md
//   node scripts/replay-timeline-report.mjs --stdout [fixtureId…]
//
// Reads tests/fixtures/replay/*.json (manifest.json). Never fetches. Pipeline:
// normalizeGame → buildStateIndex → validateReplay → buildHighlights → buildTimeline.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildHighlights } from "../lib/replay/highlights.js";
import { normalizeGame } from "../lib/replay/normalize.js";
import { buildStateIndex } from "../lib/replay/state.js";
import { TIMELINE_CONFIG, buildTimeline } from "../lib/replay/timeline.js";
import { validateReplay } from "../lib/replay/validate.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURE_DIR = join(ROOT, "tests/fixtures/replay");
const OUT = join(ROOT, "docs/replay-implementation/timeline-report.md");
const args = process.argv.slice(2);
const toStdout = args.includes("--stdout");
const manifest = JSON.parse(readFileSync(join(FIXTURE_DIR, "manifest.json"), "utf8"));
const ids = args.filter((a) => !a.startsWith("--"));
const fixtureIds = ids.length ? ids : Object.keys(manifest.fixtures);

const lines = [];
const out = (s = "") => lines.push(s);
const f1 = (x) => x.toFixed(1);
const clock = (sec) => (sec == null ? "?" : sec >= 60 ? `${Math.floor(sec / 60)}:${String(Math.floor(sec % 60)).padStart(2, "0")}` : sec.toFixed(1));

const c = TIMELINE_CONFIG;
out("# Replay timeline report (R19–R20)");
out();
out("Generated by `node scripts/replay-timeline-report.mjs` from the committed fixtures (`lib/replay/timeline.js`). Replay seconds at 1×, holds included. Scores are away–home.");
out();
out(`Defaults: target ${c.targetSec}s (+${c.overtimeExtraSec}s per OT, +${c.perMomentSec}s per moment beyond ${c.momentsBase}, clamped ${c.minSec}–${c.maxSec}s), min fast ${c.minFastSec}s, min fast gap between holds ${c.minGapSec}s, holds ${c.hold.minSec}–${c.hold.maxSec}s (by type, +${c.hold.lateBonusSec}s in the last ${c.hold.lateClockSec}s of the last regulation period / any OT), period weights Q1–Q3 ${Object.values(c.periodWeights).join("/")}, last regulation ${c.lastRegulationWeight}, OT ${c.overtimeWeight}, finish boost up to ×${1 + c.finish.maxBoost} (margin ≤ ${c.finish.closeMargin}, last ${c.finish.windowSec}s), settled ×${c.settled.factor} (margin ≥ ${c.settled.baseMargin} + ${c.settled.perMinute}/min left).`);
out();

const summary = [];
const sections = [];
for (const id of fixtureIds) {
  const n = normalizeGame(JSON.parse(readFileSync(join(FIXTURE_DIR, `${id}.json`), "utf8")));
  const idx = buildStateIndex(n);
  const v = validateReplay(n, idx);
  const { highlights } = buildHighlights(n, { stateIndex: idx, capabilities: v.capabilities });
  const tl = buildTimeline(n, highlights);
  const holds = tl.segments.filter((s) => s.kind === "hold");
  const holdTotal = holds.reduce((a, s) => a + s.endSec - s.startSec, 0);
  const reg = n.format.regulationPeriods;
  const lastReg = tl.periods.find((p) => p.period === reg);
  const finishShare = lastReg ? (lastReg.endSec - lastReg.startSec) / tl.durationSec : 0;
  const fin = n.events[n.events.length - 1].scoreAfter;
  const title = `${n.teams.away.abbreviation}@${n.teams.home.abbreviation} ${fin.away}–${fin.home}`;
  summary.push(`| ${id} | ${title} | ${n.events.length} | ${f1(tl.durationSec)} | ${holds.length} | ${f1(holdTotal)} | ${(finishShare * 100).toFixed(0)}% | ${tl.periods.map((p) => `${p.label} ${f1(p.endSec - p.startSec)}`).join(", ")} |`);
  const s = [];
  s.push(`## ${id} — ${title}`);
  s.push();
  s.push(`Status ${v.status}; ${n.events.length} events; target ${tl.targetSec}s; duration ${f1(tl.durationSec)}s; ${holds.length} holds = ${f1(holdTotal)}s; ${tl.segments.length} segments${tl.issues.length ? `; issues: ${tl.issues.map((i) => i.code).join(", ")}` : ""}.`);
  s.push("");
  s.push("| Period | Replay start | Replay sec | Share | Events |");
  s.push("| --- | ---: | ---: | ---: | ---: |");
  for (const p of tl.periods) s.push(`| ${p.label} | ${f1(p.startSec)} | ${f1(p.endSec - p.startSec)} | ${(((p.endSec - p.startSec) / tl.durationSec) * 100).toFixed(0)}% | ${p.toEventIndex - p.fromEventIndex + 1} |`);
  s.push("");
  if (tl.moments.length) {
    s.push("| Moment | Type | Game clock | Score | Replay sec | Hold |");
    s.push("| --- | --- | --- | --- | ---: | ---: |");
    for (const m of tl.moments) {
      const e = n.events[m.eventIndex];
      const pl = e.period <= reg ? `Q${e.period}` : `OT${e.period - reg}`;
      s.push(`| ${m.highlightId} | ${m.type} | ${pl} ${clock(e.clockRemainingSec)} | ${e.scoreAfter.away}–${e.scoreAfter.home} | ${f1(m.startSec)} | ${m.holdSec.toFixed(1)} |`);
    }
  } else s.push("No moments.");
  s.push("");
  sections.push(...s);
}

out("| Game | Matchup | Events | Duration s | Holds | Hold s | Last-reg. share | Per-period replay s |");
out("| --- | --- | ---: | ---: | ---: | ---: | ---: | --- |");
for (const r of summary) out(r);
out();
for (const l of sections) out(l);

const text = lines.join("\n");
if (toStdout) process.stdout.write(text);
else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
