#!/usr/bin/env node
// Highlight candidate/selection report (tasks R15–R17).
//
// Usage:
//   node scripts/replay-highlights-report.mjs [fixtureId…]          # writes docs/replay-implementation/highlights-report.md
//   node scripts/replay-highlights-report.mjs --stdout [fixtureId…]
//
// Reads tests/fixtures/replay/*.json (manifest.json). Never fetches. Runs the
// real pipeline: normalizeGame → buildStateIndex → validateReplay → buildHighlights.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { HIGHLIGHT_CONFIG, buildHighlights } from "../lib/replay/highlights.js";
import { normalizeGame } from "../lib/replay/normalize.js";
import { buildStateIndex } from "../lib/replay/state.js";
import { validateReplay } from "../lib/replay/validate.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURE_DIR = join(ROOT, "tests/fixtures/replay");
const OUT = join(ROOT, "docs/replay-implementation/highlights-report.md");
const args = process.argv.slice(2);
const toStdout = args.includes("--stdout");
const manifest = JSON.parse(readFileSync(join(FIXTURE_DIR, "manifest.json"), "utf8"));
const ids = args.filter((a) => !a.startsWith("--"));
const fixtureIds = ids.length ? ids : Object.keys(manifest.fixtures);

const NOTABLE_DROPPED = 10;
const lines = [];
const out = (s = "") => lines.push(s);

const clock = (period, sec, reg = 4) => {
  if (period == null) return "?";
  const p = period <= reg ? `Q${period}` : `OT${period - reg}`;
  if (sec == null) return `${p} ?`;
  const m = Math.floor(sec / 60);
  const s = sec - m * 60;
  return `${p} ${sec >= 60 ? `${m}:${String(Math.floor(s)).padStart(2, "0")}` : sec.toFixed(1)}`;
};

out("# Replay highlights report (R15–R17)");
out();
out("Generated by `node scripts/replay-highlights-report.mjs` from the committed fixtures. Pipeline: `normalizeGame` → `buildStateIndex` → `validateReplay` → `buildHighlights` (`lib/replay/highlights.js`, version-pinned defaults below). Scores are away–home. Probability = home win probability before → after the moment's event range; Δ is from the acting team's side.");
out();
out(`Defaults: maxHighlights ${HIGHLIGHT_CONFIG.maxHighlights}, minImportance ${HIGHLIGHT_CONFIG.minImportance}, coverage ≥ ${HIGHLIGHT_CONFIG.coverageMinImportance} (max ${HIGHLIGHT_CONFIG.coverageMaxPicks}), finish window ${HIGHLIGHT_CONFIG.finishWindowSec}s (reserve ${HIGHLIGHT_CONFIG.finishReserve}), max ${HIGHLIGHT_CONFIG.maxPerEarlyPeriod} per early period, repeat penalty ${HIGHLIGHT_CONFIG.typeRepeatPenalty}.`);
out();

const summary = [];
const sections = [];
for (const id of fixtureIds) {
  const summaryJson = JSON.parse(readFileSync(join(FIXTURE_DIR, `${id}.json`), "utf8"));
  const n = normalizeGame(summaryJson);
  const idx = buildStateIndex(n);
  const v = validateReplay(n, idx);
  const { highlights, candidates } = buildHighlights(n, { stateIndex: idx, capabilities: v.capabilities });
  const reg = n.format.regulationPeriods;
  const abbr = (t) => (t === n.teams.home.id ? n.teams.home.abbreviation : t === n.teams.away.id ? n.teams.away.abbreviation : "—");
  const name = (pid) => n.players.find((p) => p.id === pid)?.shortName ?? pid;
  const score = (s) => (s ? `${s.away}–${s.home}` : "—");
  const prob = (p) => (p ? `${p.homeBefore.toFixed(3)} → ${p.homeAfter.toFixed(3)} (Δ ${p.delta >= 0 ? "+" : ""}${p.delta.toFixed(3)})` : "—");
  const evidenceText = (c) => {
    const e = c.evidence;
    const bits = [];
    if (e.scoreBefore) bits.push(`${score(e.scoreBefore)} → ${score(e.scoreAfter)}`);
    else if (e.scoreAfter) bits.push(score(e.scoreAfter));
    if (e.intermediateTie) bits.push("via tie");
    if (e.leadEnded) bits.push(`last led until ${clock(e.leadEnded.period, e.leadEnded.clockSec, reg)} (#${e.leadEnded.eventIndex})`);
    else if (e.neverLed) bits.push("never led before");
    if (e.droughtSec != null) bits.push(`${Math.round(e.droughtSec)}s without lead, max deficit ${e.maxDeficitSinceLead}`);
    if (e.historyComplete === false) bits.push("history incomplete");
    if (e.longLeadClaimOmitted) bits.push(`long-lead claim omitted (${e.longLeadClaimOmitted})`);
    if (e.runPoints) bits.push(`run ${e.runPoints}–0`);
    if (e.stake) bits.push(`stake ${e.stake}, value ${e.attemptValue}`);
    const ver = e.verification ?? {};
    if (ver.periodEndIndex != null && c.type === "missed_final_attempt") bits.push(`[look-ahead] period end #${ver.periodEndIndex}; between: ${(ver.eventsUntilPeriodEnd ?? []).map((x) => x.kind).join(", ") || "none"}`);
    if (ver.interruptingEventIndex != null) bits.push(`[look-ahead] interrupted by #${ver.interruptingEventIndex}`);
    if (ver.nextPeriodFirstIndex != null) bits.push(`[look-ahead] next period starts #${ver.nextPeriodFirstIndex}`);
    if (e.threshold != null) bits.push(`lead first reaches ${e.threshold} (previous largest ${e.previousLargestLead})`);
    if (e.linkedTurnover != null) bits.push(`→ given back #${e.linkedTurnover}`);
    if (c.selection?.decisiveLead) bits.push("[selection] decisive lead change (+boost)");
    if (e.linkedScore) bits.push(`→ score #${e.linkedScore.from}`);
    if (e.related?.length) bits.push(`grouped: ${e.related.map((r) => r.id).join(", ")}`);
    return bits.join("; ");
  };
  const who = (c) => (c.playerIds ?? []).map(name).join(", ") || "team";
  const reasons = {};
  for (const c of candidates) if (c.status === "dropped") reasons[c.reason] = (reasons[c.reason] ?? 0) + 1;
  const m = manifest.fixtures[id];
  summary.push(`| ${id} | ${n.teams.away.abbreviation} @ ${n.teams.home.abbreviation} ${n.teams.away.finalScore}–${n.teams.home.finalScore}${m?.label ? ` (${m.label})` : ""} | ${v.status} | ${candidates.length} | ${highlights.length} | ${[...new Set(highlights.map((h) => h.type))].join(", ") || "—"} |`);

  const s = [];
  s.push(`## ${id} — ${n.teams.away.abbreviation} @ ${n.teams.home.abbreviation} ${n.teams.away.finalScore}–${n.teams.home.finalScore}`);
  s.push("");
  s.push(`Status ${v.status}. ${candidates.length} candidates, ${highlights.length} selected. Dropped: ${Object.entries(reasons).sort().map(([r, k]) => `${r} ${k}`).join(", ") || "none"}.`);
  s.push("");
  s.push("### Selected");
  s.push("");
  if (!highlights.length) s.push("_None: no candidate reaches the thresholds (no fabricated drama)._");
  else {
    s.push("| # | Moment | Clock | Team | Players | Events | Importance | Phase | Evidence | Probability |");
    s.push("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
    highlights.forEach((h, i) => {
      const cand = candidates.find((c) => c.id === h.id);
      const e = n.events[h.keyEventIndex];
      s.push(`| ${i + 1} | \`${h.id}\` | ${clock(e.period, e.clockRemainingSec, reg)} | ${h.teamIds.map(abbr).join("/")} | ${h.playerIds.map(name).join(", ") || "team"} | ${h.groupStartIndex}–${h.eventIndex} | ${h.importance.toFixed(1)} | ${cand?.selectedIn ?? ""} | ${evidenceText({ ...h, selection: cand?.selection })} | ${prob(h.evidence.probability)} |`);
    });
  }
  s.push("");
  s.push(`### Notable dropped (top ${NOTABLE_DROPPED} by importance, excluding \`routine\`)`);
  s.push("");
  const dropped = candidates.filter((c) => c.status === "dropped" && c.reason !== "routine").sort((a, b) => b.importance - a.importance || a.keyEventIndex - b.keyEventIndex).slice(0, NOTABLE_DROPPED);
  if (!dropped.length) s.push("_None._");
  else {
    s.push("| Candidate | Clock | Team | Players | Importance | Reason | Evidence |");
    s.push("| --- | --- | --- | --- | --- | --- | --- |");
    for (const c of dropped) {
      const e = n.events[c.keyEventIndex];
      s.push(`| \`${c.id}\` | ${clock(e.period, e.clockRemainingSec, reg)} | ${abbr(c.teamId)} | ${who(c)} | ${c.importance.toFixed(1)} | ${c.reason}${c.mergedInto ? ` → \`${c.mergedInto}\`` : ""} | ${evidenceText(c)} |`);
    }
  }
  s.push("");
  sections.push(...s);
}

out("## Summary");
out();
out("| Game | Matchup | Status | Candidates | Selected | Types |");
out("| --- | --- | --- | --- | --- | --- |");
summary.forEach((l) => out(l));
out();
sections.forEach((l) => out(l));

const text = lines.join("\n");
if (toStdout) console.log(text);
else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
